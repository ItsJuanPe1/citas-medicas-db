-- =====================================================================
-- Optimizacion idempotente para bases de datos ya cargadas (PROYECTOPLSQL).
-- Crea indices secundarios en PROYECTOPLSQL_IDX si no existen, activa CACHE
-- en las secuencias SEQ_TBL_* y actualiza estadisticas del optimizador.
-- No borra ni modifica datos.
-- =====================================================================

DECLARE
    PROCEDURE PRO_CREAR_INDICE_SI_NO_EXISTE(ps_nombre IN VARCHAR2, ps_ddl IN VARCHAR2) IS
        vn_existe NUMBER;
    BEGIN
        SELECT COUNT(*) INTO vn_existe
          FROM USER_INDEXES
         WHERE INDEX_NAME = UPPER(ps_nombre);
        IF vn_existe = 0 THEN
            EXECUTE IMMEDIATE ps_ddl;
        END IF;
    END PRO_CREAR_INDICE_SI_NO_EXISTE;
BEGIN
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_USUARIOS_ROL',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_USUARIOS_ROL ON PROYECTOPLSQL.TBL_USUARIOS(ID_ROL) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_PARAMETRICA_NOM_VAL',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_PARAMETRICA_NOM_VAL ON PROYECTOPLSQL.TBL_PARAMETRICA_TIPOS(NOMBRE, VALOR) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_LOG_AUD_FECHA',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_LOG_AUD_FECHA ON PROYECTOPLSQL.TBL_LOG_AUDITORIAS(FECHA_HORA DESC, ID_LOG DESC) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_LOG_AUD_TABLA_REG',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_LOG_AUD_TABLA_REG ON PROYECTOPLSQL.TBL_LOG_AUDITORIAS(TABLA_AFECTADA, ACCION, ID_REGISTRO) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_MEDICOS_ESP',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_MEDICOS_ESP ON PROYECTOPLSQL.TBL_MEDICOS(ID_ESPECIALIDAD) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_AGENDAS_MED_FECHAS',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_AGENDAS_MED_FECHAS ON PROYECTOPLSQL.TBL_AGENDAS_MEDICOS(ID_MEDICO, FECHA_HORA_FIN, FECHA_HORA_INICIO) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_AGENDAS_EST_FECHAS',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_AGENDAS_EST_FECHAS ON PROYECTOPLSQL.TBL_AGENDAS_MEDICOS(ID_ESTADO, FECHA_HORA_FIN, FECHA_HORA_INICIO) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_CITAS_PACIENTE_INI',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_CITAS_PACIENTE_INI ON PROYECTOPLSQL.TBL_CITAS_MEDICAS(ID_PACIENTE, FECHA_HORA_INICIO DESC) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_CITAS_INI_ESTADO',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_CITAS_INI_ESTADO ON PROYECTOPLSQL.TBL_CITAS_MEDICAS(FECHA_HORA_INICIO, ID_ESTADO) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_RECETAS_EMISION_EST',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_RECETAS_EMISION_EST ON PROYECTOPLSQL.TBL_RECETAS_MEDICAS(FECHA_EMISION, ID_ESTADO) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_DET_RECETA_RECETA',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_DET_RECETA_RECETA ON PROYECTOPLSQL.TBL_DETALLE_RECETA(ID_RECETA) TABLESPACE PROYECTOPLSQL_IDX'
    );
    PRO_CREAR_INDICE_SI_NO_EXISTE(
        'IDX_TBL_DET_RECETA_PEND',
        'CREATE INDEX PROYECTOPLSQL.IDX_TBL_DET_RECETA_PEND ON PROYECTOPLSQL.TBL_DETALLE_RECETA(CANTIDAD_PENDIENTE) TABLESPACE PROYECTOPLSQL_IDX'
    );
END;
