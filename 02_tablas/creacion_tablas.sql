-- Teardown idempotente: recorre el diccionario del usuario y borra solo si existe.
-- CASCADE CONSTRAINTS evita problemas de orden entre tablas con FK.
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('STOCK_FARMACIA','DETALLE_RECETA','MEDICAMENTOS','RECETAS_MEDICAS',
                                 'HISTORIA_CLINICA','CITAS_MEDICAS','PACIENTES','AGENDAS_MEDICOS',
                                 'FARMACEUTICOS','MEDICOS','LOG_AUDITORIAS','PARAMETRICA_TIPOS',
                                 'USUARIOS','ROLES')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
  FOR s IN (SELECT sequence_name FROM user_sequences
            WHERE sequence_name IN ('SEQ_ROLES','SEQ_USUARIOS','SEQ_PARAMETRICA_TIPOS','SEQ_LOG_AUDITORIAS',
                                    'SEQ_MEDICOS','SEQ_FARMACEUTICOS','SEQ_AGENDAS_MEDICOS','SEQ_PACIENTES',
                                    'SEQ_CITAS_MEDICAS','SEQ_HISTORIA_CLINICA','SEQ_RECETAS_MEDICAS',
                                    'SEQ_MEDICAMENTOS','SEQ_DETALLE_RECETA','SEQ_STOCK_FARMACIA')) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
  END LOOP;
END;
/

-- 1. ROLES
CREATE TABLE ROLES(
ID_ROL NUMBER(10),
NOMBRE VARCHAR2(50),
DESCRIPCION VARCHAR2(255),
CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)TABLESPACE PROYECTOPLSQL_DAT;

CREATE UNIQUE INDEX IDX_PK_ROLES ON PROYECTOPLSQL.ROLES(ID_ROL) TABLESPACE PROYECTOPLSQL_IDX;

ALTER TABLE PROYECTOPLSQL.ROLES ADD CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL) USING INDEX IDX_PK_ROLES;

-- 2. USUARIOS
-- Solo credenciales y acceso. Los datos personales viven en MEDICOS / PACIENTES / FARMACEUTICOS.
-- ID_ENTIDAD guarda el id de la tabla que corresponda segun el rol (MEDICO -> MEDICOS,
-- PACIENTE -> PACIENTES, FARMACEUTICO -> FARMACEUTICOS). NO tiene FK a proposito (apunta a varias tablas).
-- Es NULL para los roles sin entidad (superadmin, gerente, recepcionista1, recepcionista2, ...).
-- PASSWORD guarda el hash de la clave, nunca la clave en texto plano.
CREATE TABLE USUARIOS(
ID_USUARIO NUMBER(10),
ID_ROL NUMBER(10) NOT NULL,
USERNAME VARCHAR2(50) NOT NULL,
PASSWORD VARCHAR2(255) NOT NULL,
ID_ENTIDAD NUMBER(10),
ESTADO VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CONSTRAINT UQ_USUARIOS_USERNAME UNIQUE (USERNAME),
CONSTRAINT CK_USUARIOS_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
CONSTRAINT FK_USUARIOS_ROLES FOREIGN KEY (ID_ROL)
REFERENCES ROLES (ID_ROL)
)TABLESPACE PROYECTOPLSQL_DAT;

CREATE UNIQUE INDEX IDX_PK_USUARIOS ON PROYECTOPLSQL.USUARIOS(ID_USUARIO) TABLESPACE PROYECTOPLSQL_IDX;

ALTER TABLE PROYECTOPLSQL.USUARIOS ADD CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO) USING INDEX IDX_PK_USUARIOS;

-- 3. PARAMETRICA_TIPOS
-- Las FK de otras tablas apuntan a ID_PARAMETRO (la PK).
-- ID_TIPO es el codigo unico del valor. NOMBRE agrupa los valores:
--   ESPECIALIDAD (tipo de medico), TIPO_MEDICAMENTO, ESTADO_CITA, ESTADO_RECETA,
--   ESTADO_DETALLE_RECETA, ESTADO_AGENDA.
CREATE TABLE PARAMETRICA_TIPOS(
ID_PARAMETRO NUMBER(10),
ID_TIPO NUMBER(10) NOT NULL,
NOMBRE VARCHAR2(50) NOT NULL,
VALOR VARCHAR2(100) NOT NULL,
DESCRIPCION VARCHAR2(255) NOT NULL,
CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CONSTRAINT UQ_PARAMETRICA_TIPOS_TIPO UNIQUE (ID_TIPO)
)TABLESPACE PROYECTOPLSQL_DAT;

CREATE UNIQUE INDEX IDX_PK_PARAMETRICA_TIPOS ON PROYECTOPLSQL.PARAMETRICA_TIPOS(ID_PARAMETRO) TABLESPACE PROYECTOPLSQL_IDX;

ALTER TABLE PROYECTOPLSQL.PARAMETRICA_TIPOS ADD CONSTRAINT PK_PARAMETRICA_TIPOS PRIMARY KEY (ID_PARAMETRO) USING INDEX IDX_PK_PARAMETRICA_TIPOS;

-- 4. LOG_AUDITORIAS (bitacora generica)
-- ID_REGISTRO = valor de la llave primaria del registro afectado en TABLA_AFECTADA
-- (por ejemplo, TABLA_AFECTADA = 'CITAS_MEDICAS' e ID_REGISTRO = 15 -> la cita 15).
-- Sin FK: ID_USUARIO lo trae la programacion (el id del usuario que hizo el cambio) pero no se relaciona en la BD.
CREATE TABLE LOG_AUDITORIAS(
ID_LOG NUMBER(10),
ID_USUARIO NUMBER(10) NOT NULL,
ACCION VARCHAR2(50) NOT NULL,
TABLA_AFECTADA VARCHAR2(100) NOT NULL,
ID_REGISTRO NUMBER(10) NOT NULL,
VALOR_ANTES VARCHAR2(4000),
VALOR_DESPUES VARCHAR2(4000),
FECHA_HORA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)TABLESPACE PROYECTOPLSQL_DAT;

CREATE UNIQUE INDEX IDX_PK_LOG_AUDITORIAS ON PROYECTOPLSQL.LOG_AUDITORIAS(ID_LOG) TABLESPACE PROYECTOPLSQL_IDX;

ALTER TABLE PROYECTOPLSQL.LOG_AUDITORIAS ADD CONSTRAINT PK_LOG_AUDITORIAS PRIMARY KEY (ID_LOG) USING INDEX IDX_PK_LOG_AUDITORIAS;

