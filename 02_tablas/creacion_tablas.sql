-- 11. RECETAS_MEDICAS (1 historia = maximo 1 receta)
-- ID_ESTADO apunta a PARAMETRICA_TIPOS.ID_PARAMETRO (ESTADO_RECETA: NO ENTREGADA / PARCIALMENTE / ENTREGADA)
-- El estado lo calcula el sistema (trigger sobre DETALLE_RECETA): todos los detalles entregados ->
-- ENTREGADA; algunos -> PARCIALMENTE; ninguno -> NO ENTREGADA. El farmaceutico no lo cambia a mano.
CREATE TABLE RECETAS_MEDICAS(
ID_RECETA NUMBER(10),
ID_HISTORIA NUMBER(10) NOT NULL,
ID_ESTADO NUMBER(10) NOT NULL,
FECHA_EMISION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CONSTRAINT UQ_RECETAS_MEDICAS_HISTORIA UNIQUE (ID_HISTORIA),
CONSTRAINT FK_RECETAS_MEDICAS_HISTORIA FOREIGN KEY (ID_HISTORIA)
REFERENCES HISTORIA_CLINICA (ID_HISTORIA),
CONSTRAINT FK_RECETAS_MEDICAS_ESTADO FOREIGN KEY (ID_ESTADO)
REFERENCES PARAMETRICA_TIPOS (ID_PARAMETRO)
)TABLESPACE PROYECTOPLSQL_DAT;

CREATE UNIQUE INDEX IDX_PK_RECETAS_MEDICAS ON PROYECTOPLSQL.RECETAS_MEDICAS(ID_RECETA) TABLESPACE PROYECTOPLSQL_IDX;

ALTER TABLE PROYECTOPLSQL.RECETAS_MEDICAS ADD CONSTRAINT PK_RECETAS_MEDICAS PRIMARY KEY (ID_RECETA) USING INDEX IDX_PK_RECETAS_MEDICAS;

