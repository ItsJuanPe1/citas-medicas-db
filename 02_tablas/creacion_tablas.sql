-- Teardown idempotente: recorre el diccionario del usuario y borra solo si existe.
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('TBL_STOCK_FARMACIA','TBL_DETALLE_RECETA','TBL_MEDICAMENTOS','TBL_RECETAS_MEDICAS',
                                 'TBL_HISTORIA_CLINICA','TBL_CITAS_MEDICAS','TBL_PACIENTES','TBL_AGENDAS_MEDICOS',
                                 'TBL_FARMACEUTICOS','TBL_MEDICOS','TBL_LOG_AUDITORIAS','TBL_PARAMETRICA_TIPOS',
                                 'TBL_USUARIOS','TBL_ROLES')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;

  FOR s IN (SELECT sequence_name FROM user_sequences
            WHERE sequence_name IN ('SEQ_TBL_ROLES','SEQ_TBL_USUARIOS','SEQ_TBL_PARAMETRICA_TIPOS','SEQ_TBL_LOG_AUDITORIAS',
                                    'SEQ_TBL_MEDICOS','SEQ_TBL_FARMACEUTICOS','SEQ_TBL_AGENDAS_MEDICOS','SEQ_TBL_PACIENTES',
                                    'SEQ_TBL_CITAS_MEDICAS','SEQ_TBL_HISTORIA_CLINICA','SEQ_TBL_RECETAS_MEDICAS',
                                    'SEQ_TBL_MEDICAMENTOS','SEQ_TBL_DETALLE_RECETA','SEQ_TBL_STOCK_FARMACIA')) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
  END LOOP;
END;
/

