-- 13. DETALLE_RECETA
-- ID_ESTADO apunta a PARAMETRICA_TIPOS.ID_PARAMETRO (ESTADO_DETALLE_RECETA: ENTREGADO / NO ENTREGADO).
-- ENTREGADO = el farmaceutico le puso el chulo (CANTIDAD_PENDIENTE = 0).
-- CANTIDAD = unidades recetadas; CANTIDAD_PENDIENTE = unidades que faltan por entregar
-- (el farmaceutico puede entregar parte, por ejemplo 3 de 6 por falta de stock).
-- ID_FARMACEUTICO queda NULL mientras no se ha entregado nada de ese medicamento.
CREATE TABLE DETALLE_RECETA(
ID_DETALLE NUMBER(10),
ID_RECETA NUMBER(10) NOT NULL,
ID_MEDICAMENTO NUMBER(10) NOT NULL,
ID_FARMACEUTICO NUMBER(10),
ID_ESTADO NUMBER(10) NOT NULL,
CANTIDAD NUMBER(5) NOT NULL,
CANTIDAD_PENDIENTE NUMBER(5) NOT NULL,
DOSIS VARCHAR2(100),
CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CONSTRAINT CK_DETALLE_RECETA_CANTIDAD CHECK (CANTIDAD > 0),
CONSTRAINT CK_DETALLE_RECETA_PENDIENTE CHECK (CANTIDAD_PENDIENTE >= 0 AND CANTIDAD_PENDIENTE <= CANTIDAD),
CONSTRAINT FK_DETALLE_RECETA_RECETAS FOREIGN KEY (ID_RECETA)
REFERENCES RECETAS_MEDICAS (ID_RECETA),
CONSTRAINT FK_DETALLE_RECETA_MEDICAMENTOS FOREIGN KEY (ID_MEDICAMENTO)
REFERENCES MEDICAMENTOS (ID_MEDICAMENTO),
CONSTRAINT FK_DETALLE_RECETA_FARMACEUTICOS FOREIGN KEY (ID_FARMACEUTICO)
REFERENCES FARMACEUTICOS (ID_FARMACEUTICO),
CONSTRAINT FK_DETALLE_RECETA_ESTADO FOREIGN KEY (ID_ESTADO)
REFERENCES PARAMETRICA_TIPOS (ID_PARAMETRO)
)TABLESPACE PROYECTOPLSQL_DAT;

CREATE UNIQUE INDEX IDX_PK_DETALLE_RECETA ON PROYECTOPLSQL.DETALLE_RECETA(ID_DETALLE) TABLESPACE PROYECTOPLSQL_IDX;

ALTER TABLE PROYECTOPLSQL.DETALLE_RECETA ADD CONSTRAINT PK_DETALLE_RECETA PRIMARY KEY (ID_DETALLE) USING INDEX IDX_PK_DETALLE_RECETA;

