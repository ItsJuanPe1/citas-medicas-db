-- Esquema y tablespaces (PROYECTOPLSQL / PROYECTOPLSQL_DAT / PROYECTOPLSQL_IDX).
-- Version 2: ajustes de la retroalimentacion de clase (LOG, USUARIOS, FARMACEUTICOS,
--            estados en PARAMETRICA_TIPOS, entrega de medicamentos por farmaceutico).
